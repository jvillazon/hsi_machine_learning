#!/usr/bin/env python3
"""
convert_roi_cells_to_gui_format.py
==================================
Converts cell segmentation Parquet/CSV files (such as those generated by
read_parquet.ipynb or Xenium pipeline steps) into standard GUI-compatible
ROI tables directly loadable by multimodal_napari_gui (via load_napari_rois).

Supported input formats:
- Per-vertex tables with columns like ['cell_id', 'x_roi', 'y_roi', 'levelKID_refined']
- Per-vertex tables with ['cell_id', 'x', 'y', 'group'] or ['vertex_x', 'vertex_y']
- Single file or batch directory processing.

Output format:
- Parquet and/or CSV containing:
  ['Sample_ID', 'ROI_Number', 'ROI_instance', 'Region_Index', 'Label',
   'Fluorescence_Label', 'Vertex_Count', 'Geometry_WKT', 'Vertices_JSON',
   'Centroid_X', 'Centroid_Y', 'Area_px', 'UID', 'cell_id', 'Image_Name', 'Image_Path']
- Optional labeled mask TIFF and legend JSON.
"""

import os
import sys
import glob
import json
import time
import argparse
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union

import numpy as np
import pandas as pd
import shapely.geometry as sg
import tifffile

try:
    import cv2
except ImportError:
    cv2 = None


def compute_polygon_area(pts: np.ndarray) -> float:
    """Compute polygon area using Shoelace formula or Shapely."""
    if len(pts) < 3:
        return 0.0
    try:
        poly = sg.Polygon(pts)
        if poly.is_valid:
            return float(poly.area)
    except Exception:
        pass
    # Shoelace fallback
    x = pts[:, 0]
    y = pts[:, 1]
    return float(0.5 * np.abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1))))


def auto_detect_columns(
    df: pd.DataFrame,
    cell_col: Optional[str] = None,
    label_col: Optional[str] = None,
    x_col: Optional[str] = None,
    y_col: Optional[str] = None,
) -> Tuple[str, str, str, str]:
    """Auto-detect column names for cell_id, label, x, and y coordinates."""
    # X coordinate
    if x_col and x_col in df.columns:
        res_x = x_col
    else:
        for candidate in ["x_roi", "x", "vertex_x", "x_px", "X", "Centroid_X", "centroid_x"]:
            if candidate in df.columns:
                res_x = candidate
                break
        else:
            raise ValueError(f"Could not find X coordinate column. Available columns: {list(df.columns)}")

    # Y coordinate
    if y_col and y_col in df.columns:
        res_y = y_col
    else:
        for candidate in ["y_roi", "y", "vertex_y", "y_px", "Y", "Centroid_Y", "centroid_y"]:
            if candidate in df.columns:
                res_y = candidate
                break
        else:
            raise ValueError(f"Could not find Y coordinate column. Available columns: {list(df.columns)}")

    # Cell ID
    if cell_col and cell_col in df.columns:
        res_cell = cell_col
    else:
        for candidate in ["cell_id", "cell_ID", "UID", "Cell_ID", "cell", "id"]:
            if candidate in df.columns:
                res_cell = candidate
                break
        else:
            res_cell = df.columns[0]

    # Label / Annotation
    if label_col and label_col in df.columns:
        res_label = label_col
    else:
        for candidate in ["levelKID_refined", "group", "Label", "Fluorescence_Label", "cell_type", "cluster", "annotation", "class"]:
            if candidate in df.columns:
                res_label = candidate
                break
        else:
            res_label = res_cell

    return res_cell, res_label, res_x, res_y


def parse_sample_and_roi_name(file_path: str, user_sample: str = "", user_roi: str = "") -> Tuple[str, str]:
    """Extract sample ID and ROI name from filename if not explicitly provided."""
    stem = Path(file_path).stem
    
    # Auto ROI Name
    if user_roi:
        roi_name = user_roi
    elif "-roi" in stem.lower() or "_roi" in stem.lower():
        # E.g. aki_cell_segmentation-roi1_cells -> roi1
        parts = stem.replace("_", "-").split("-")
        roi_parts = [p for p in parts if p.lower().startswith("roi")]
        roi_name = roi_parts[0] if roi_parts else stem
    elif "roi" in stem.lower():
        roi_name = stem
    else:
        roi_name = stem

    # Auto Sample ID
    if user_sample:
        sample_id = user_sample
    else:
        parts = stem.split("_")
        sample_id = parts[0] if len(parts) > 0 else "sample"

    return sample_id, roi_name


def convert_single_file(
    input_path: str,
    output_path: Optional[str] = None,
    cell_col: Optional[str] = None,
    label_col: Optional[str] = None,
    x_col: Optional[str] = None,
    y_col: Optional[str] = None,
    sample_id: str = "",
    roi_name: str = "",
    image_path: str = "",
    exclude_labels: Optional[List[str]] = None,
    include_labels: Optional[List[str]] = None,
    flip_y: bool = False,
    flip_y_height: Optional[float] = None,
    min_vertices: int = 3,
    generate_mask: bool = False,
    export_format: str = "both",  # 'parquet', 'csv', 'both'
) -> Tuple[pd.DataFrame, Dict[str, str]]:
    """
    Convert a single cell segmentation parquet/csv to GUI format.
    """
    t0 = time.time()
    input_path = os.path.abspath(input_path)
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Input file does not exist: {input_path}")

    ext = os.path.splitext(input_path)[1].lower()
    print("=" * 70)
    print("CONVERTING CELL SEGMENTATION TO GUI FORMAT")
    print("=" * 70)
    print(f"Input File     : {input_path}")

    if ext == ".parquet":
        df_raw = pd.read_parquet(input_path)
    else:
        df_raw = pd.read_csv(input_path)

    # Check if already in aggregated format (has Vertices_JSON)
    if "Vertices_JSON" in df_raw.columns:
        print(f"File already contains 'Vertices_JSON' ({len(df_raw):,} records). Verifying GUI columns...")
        df_gui = df_raw.copy()
        # Ensure all standard columns exist
        if "Sample_ID" not in df_gui.columns:
            df_gui["Sample_ID"] = sample_id or "Sample"
        if "Image_Name" not in df_gui.columns:
            df_gui["Image_Name"] = roi_name or Path(input_path).stem
        if "Image_Path" not in df_gui.columns:
            df_gui["Image_Path"] = image_path
        if "Label" not in df_gui.columns:
            df_gui["Label"] = df_gui.get("Fluorescence_Label", "Cell")
        if "Fluorescence_Label" not in df_gui.columns:
            df_gui["Fluorescence_Label"] = df_gui["Label"]
    else:
        # Resolve columns
        c_cell, c_label, c_x, c_y = auto_detect_columns(
            df_raw, cell_col=cell_col, label_col=label_col, x_col=x_col, y_col=y_col
        )
        print(f"Detected Columns: Cell ID = '{c_cell}', Label = '{c_label}', X = '{c_x}', Y = '{c_y}'")

        # Resolve sample & ROI names
        auto_sample, auto_roi = parse_sample_and_roi_name(input_path, user_sample=sample_id, user_roi=roi_name)
        print(f"Sample ID: {auto_sample}, Image / ROI Name: {auto_roi}")

        # Filter labels if specified
        if exclude_labels:
            ex_set = set(str(l).strip() for l in exclude_labels)
            df_raw = df_raw[~df_raw[c_label].astype(str).isin(ex_set)].copy()
            print(f"Excluded labels {ex_set}. Remaining rows: {len(df_raw):,}")

        if include_labels:
            inc_set = set(str(l).strip() for l in include_labels)
            df_raw = df_raw[df_raw[c_label].astype(str).isin(inc_set)].copy()
            print(f"Filtered to included labels {inc_set}. Remaining rows: {len(df_raw):,}")

        if df_raw.empty:
            raise ValueError("No rows remaining after label filtering!")

        # Coordinates & group splits
        c_ids = df_raw[c_cell].astype(str).values
        lbls = df_raw[c_label].astype(str).values
        vx = df_raw[c_x].values.astype(np.float64)
        vy = df_raw[c_y].values.astype(np.float64)

        if flip_y:
            h = flip_y_height if flip_y_height is not None else (np.max(vy) + np.min(vy))
            print(f"Inverting Y axis: y = {h:.1f} - y")
            vy = h - vy

        change_idx = np.where(c_ids[:-1] != c_ids[1:])[0] + 1
        splits_xy = np.split(np.column_stack((vx, vy)), change_idx)
        splits_c = np.split(c_ids, change_idx)
        splits_l = np.split(lbls, change_idx)

        records = []
        label_counters = {}
        for idx, (pts, c_arr, l_arr) in enumerate(zip(splits_xy, splits_c, splits_l), start=1):
            if len(pts) < min_vertices:
                continue

            c_id = str(c_arr[0])
            lbl = str(l_arr[0])
            label_counters[lbl] = label_counters.get(lbl, 0) + 1
            roi_inst = label_counters[lbl]

            # Ensure closed polygon for WKT
            if len(pts) >= 2 and not np.allclose(pts[0], pts[-1]):
                pts_closed = np.vstack([pts, pts[0]])
            else:
                pts_closed = pts

            pts_list = pts_closed.round(3).tolist()
            wkt = "POLYGON ((" + ", ".join(f"{x:.3f} {y:.3f}" for x, y in pts_closed) + "))"
            cx = float(np.mean(pts[:, 0]))
            cy = float(np.mean(pts[:, 1]))
            area = compute_polygon_area(pts)

            records.append({
                "Sample_ID": auto_sample,
                "ROI_Number": idx,
                "ROI_instance": roi_inst,
                "Region_Index": idx,
                "Label": lbl,
                "Fluorescence_Label": lbl,
                "Vertex_Count": len(pts_closed),
                "Geometry_WKT": wkt,
                "Vertices_JSON": json.dumps(pts_list),
                "Centroid_X": round(cx, 3),
                "Centroid_Y": round(cy, 3),
                "Area_px": round(area, 2),
                "UID": c_id,
                "cell_id": c_id,
                "Image_Name": auto_roi,
                "Image_Path": image_path,
            })

        df_gui = pd.DataFrame(records)
        print(f"Aggregated {len(df_gui):,} polygon ROIs from {len(df_raw):,} vertices.")

    # Determine output path
    if output_path:
        out_base = os.path.splitext(output_path)[0]
    else:
        in_stem = Path(input_path).stem
        in_dir = os.path.dirname(input_path)
        out_base = os.path.join(in_dir, f"{in_stem}_gui_rois")

    out_dir = os.path.dirname(os.path.abspath(out_base))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    saved_files = {}

    if export_format in ("parquet", "both"):
        p_path = f"{out_base}.parquet"
        df_gui.to_parquet(p_path, index=False)
        sz_mb = os.path.getsize(p_path) / (1024 * 1024)
        print(f"Saved GUI Parquet : {p_path} ({sz_mb:.2f} MB)")
        saved_files["parquet"] = p_path

    if export_format in ("csv", "both"):
        c_path = f"{out_base}.csv"
        df_gui.to_csv(c_path, index=False)
        sz_mb = os.path.getsize(c_path) / (1024 * 1024)
        print(f"Saved GUI CSV     : {c_path} ({sz_mb:.2f} MB)")
        saved_files["csv"] = c_path

    # Optional Mask Generation
    if generate_mask and not df_gui.empty:
        max_x = int(np.ceil(df_gui["Centroid_X"].max() + 50))
        max_y = int(np.ceil(df_gui["Centroid_Y"].max() + 50))
        mask_arr = np.zeros((max_y, max_x), dtype=np.uint16)

        unique_labels = df_gui["Label"].unique().tolist()
        label_to_id = {l: i + 1 for i, l in enumerate(unique_labels)}

        for _, row in df_gui.iterrows():
            lbl = row["Label"]
            val = label_to_id.get(lbl, 1)
            pts = np.array(json.loads(row["Vertices_JSON"]))
            if val > 0 and len(pts) >= 3:
                pts_round = np.round(pts).astype(np.int32)
                if cv2 is not None:
                    cv2.fillPoly(mask_arr, [pts_round], val)

        mask_tif = f"{out_base}_mask.tif"
        tifffile.imwrite(
            mask_tif,
            mask_arr,
            imagej=True,
            metadata={"axes": "YX", "unit": "pixel"},
        )
        print(f"Saved Labeled Mask: {mask_tif}")
        saved_files["mask"] = mask_tif

        legend_json = f"{out_base}_legend.json"
        with open(legend_json, "w") as f:
            json.dump({"label_to_id": label_to_id}, f, indent=2)
        saved_files["legend"] = legend_json

    print(f"Conversion completed in {time.time() - t0:.2f}s.")
    return df_gui, saved_files


def batch_convert(
    input_dir: str,
    output_dir: Optional[str] = None,
    pattern: str = "*_cells.parquet",
    **kwargs,
) -> List[Tuple[str, pd.DataFrame]]:
    """Convert all matching files in a directory."""
    files = sorted(glob.glob(os.path.join(input_dir, pattern)))
    if not files:
        # Fallback to general .parquet
        files = sorted(glob.glob(os.path.join(input_dir, "*.parquet")))

    print(f"Found {len(files)} files matching '{pattern}' in {input_dir}")
    results = []
    for f in files:
        out_path = None
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)
            out_path = os.path.join(output_dir, f"{Path(f).stem}_gui_rois")
        try:
            df, _ = convert_single_file(f, output_path=out_path, **kwargs)
            results.append((f, df))
        except Exception as e:
            print(f"Error converting {f}: {e}")
    return results


def main():
    parser = argparse.ArgumentParser(
        description="Convert cell segmentation Parquet/CSV files into standard Napari GUI-compatible ROI format."
    )
    parser.add_argument("--input", "-i", required=True, help="Path to input Parquet/CSV file or directory for batch conversion")
    parser.add_argument("--output", "-o", default=None, help="Output file path (prefix) or directory for batch mode")
    parser.add_argument("--pattern", default="*_cells.parquet", help="File pattern for batch directory mode (default: '*_cells.parquet')")
    parser.add_argument("--cell-col", default=None, help="Cell ID column (auto-detected if omitted)")
    parser.add_argument("--label-col", default=None, help="Label column (auto-detected if omitted)")
    parser.add_argument("--x-col", default=None, help="X coordinate column (auto-detected if omitted)")
    parser.add_argument("--y-col", default=None, help="Y coordinate column (auto-detected if omitted)")
    parser.add_argument("--sample-id", default="", help="Sample ID (auto-extracted from filename if omitted)")
    parser.add_argument("--image-name", default="", help="Image / ROI name (auto-extracted from filename if omitted)")
    parser.add_argument("--image-path", default="", help="Associated microscopy image path")
    parser.add_argument("--exclude-labels", default="", help="Comma-separated list of labels to exclude (e.g. 'low_quality,unassigned')")
    parser.add_argument("--include-labels", default="", help="Comma-separated list of labels to include exclusively")
    parser.add_argument("--flip-y", action="store_true", default=False, help="Invert Y axis coordinates")
    parser.add_argument("--generate-mask", action="store_true", default=False, help="Generate labeled mask TIFF")
    parser.add_argument("--format", choices=["parquet", "csv", "both"], default="both", help="Export format (default: 'both')")

    args = parser.parse_args()

    ex_labels = [s.strip() for s in args.exclude_labels.split(",") if s.strip()] if args.exclude_labels else None
    inc_labels = [s.strip() for s in args.include_labels.split(",") if s.strip()] if args.include_labels else None

    if os.path.isdir(args.input):
        batch_convert(
            input_dir=args.input,
            output_dir=args.output,
            pattern=args.pattern,
            cell_col=args.cell_col,
            label_col=args.label_col,
            x_col=args.x_col,
            y_col=args.y_col,
            sample_id=args.sample_id,
            roi_name=args.image_name,
            image_path=args.image_path,
            exclude_labels=ex_labels,
            include_labels=inc_labels,
            flip_y=args.flip_y,
            generate_mask=args.generate_mask,
            export_format=args.format,
        )
    else:
        convert_single_file(
            input_path=args.input,
            output_path=args.output,
            cell_col=args.cell_col,
            label_col=args.label_col,
            x_col=args.x_col,
            y_col=args.y_col,
            sample_id=args.sample_id,
            roi_name=args.image_name,
            image_path=args.image_path,
            exclude_labels=ex_labels,
            include_labels=inc_labels,
            flip_y=args.flip_y,
            generate_mask=args.generate_mask,
            export_format=args.format,
        )


if __name__ == "__main__":
    main()
